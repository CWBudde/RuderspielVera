// The German texts of the rule data live in the JSON files next to the numbers; their English
// translations live in i18n/en.json, keyed like TextEntries. `just gen-i18n` writes both into
// web/src/i18n/data.gen.ts, where the frontend looks them up (the engine only emits keys).

//go:embed i18n/*.json
var i18nFiles embed.FS

// TextEntry is one translatable data text.
type TextEntry struct {
	Key  string // e.g. "data.event.phoenix.name"
	Text string // German
}

func raceTextKey(comp, variant, race string) string {
	if variant == "" {
		return "data.race." + comp + "." + race + ".name"
	}

	return "data.race." + comp + "." + variant + "." + race + ".name"
}

// TextEntries lists every translatable text of the rule data in a stable order.
func (d *Data) TextEntries() []TextEntry {
	var out []TextEntry

	add := func(key, text string) {
		if text != "" {
			out = append(out, TextEntry{Key: key, Text: text})
		}
	}

	for _, st := range d.Calendar {
		add("data.station."+st.ID+".name", st.Name)
		add("data.station."+st.ID+".info", st.Info)
	}

	for _, id := range sortedKeys(d.Competitions) {
		c := d.Competitions[id]
		add("data.competition."+id+".name", c.Name)

		for i, n := range c.Notes {
			add("data.competition."+id+".notes."+strconv.Itoa(i), n)
		}

		for _, r := range c.Races {
			add(r.TextKey, r.Name)
		}

		for _, v := range sortedKeys(c.Variants) {
			for _, r := range c.Variants[v] {
				add(r.TextKey, r.Name)
			}
		}
	}

	for _, e := range d.Events {
		add("data.event."+e.Type+".name", e.Name)
		add("data.event."+e.Type+".description", e.Description)
	}

	for _, e := range d.Ereignisse {
		add("data.ereignis."+e.ID+".name", e.Name)
		add("data.ereignis."+e.ID+".description", e.Description)
	}

	for _, m := range d.Missions {
		add("data.mission."+m.ID+".text", m.Text)
		add("data.mission."+m.ID+".reward", m.RewardText)
	}

	for _, t := range d.Trainers {
		add("data.trainer."+t.ID+".name", t.Name)
		add("data.trainer."+t.ID+".ability", t.Ability)
		add("data.trainer."+t.ID+".description", t.Description)
	}

	for _, b := range d.Boats {
		add("data.boat."+b.ID+".name", b.Name)
	}

	for _, id := range sortedKeys(d.Rules.Selections) {
		add("data.selection."+id+".label", d.Rules.Selections[id].Label)
	}

	add("data.guest.name", d.Rules.Guests.Name)

	return out
}

// Translations returns the data texts of a language other than German (i18n/<lang>.json).
func Translations(lang string) (map[string]string, error) {
	raw, err := i18nFiles.ReadFile("i18n/" + lang + ".json")
	if err != nil {
		return nil, fmt.Errorf("read i18n/%s.json: %w", lang, err)
	}

	var m map[string]string

	err = json.Unmarshal(raw, &m)
	if err != nil {
		return nil, fmt.Errorf("i18n/%s.json: %w", lang, err)
	}

	return m, nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}

	slices.SortFunc(keys, strings.Compare)

	return keys
}

// GenerateTS renders web/src/i18n/data.gen.ts: the German data texts and their English
// translations as flat key → text maps. Missing English texts are left out (the UI falls back to
// German); TestDataTranslations reports them.
func (d *Data) GenerateTS() ([]byte, error) {
	en, err := Translations("en")
	if err != nil {
		return nil, err
	}

	var b strings.Builder

	b.WriteString("// Code generated by `just gen-i18n` from internal/data (German) and internal/data/i18n/en.json. DO NOT EDIT.\n\n")

	write := func(name string, text func(TextEntry) (string, bool)) error {
		fmt.Fprintf(&b, "export const %s: Record<string, string> = {\n", name)

		for _, e := range d.TextEntries() {
			s, ok := text(e)
			if !ok {
				continue
			}

			k, err := json.Marshal(e.Key)
			if err != nil {
				return err
			}

			v, err := json.Marshal(s)
			if err != nil {
				return err
			}

			fmt.Fprintf(&b, "  %s: %s,\n", k, v)
		}

		b.WriteString("};\n")

		return nil
	}

	err = write("dataDe", func(e TextEntry) (string, bool) { return e.Text, true })
	if err != nil {
		return nil, err
	}

	b.WriteString("\n")

	err = write("dataEn", func(e TextEntry) (string, bool) {
		s, ok := en[e.Key]
		return s, ok
	})
	if err != nil {
		return nil, err
	}

	return []byte(b.String()), nil
}
