// Command sim plays all-bot seasons and prints balancing statistics.
//
//	go run ./cmd/sim -games 1000 -seed 1 [-players 3] [-mode default|taktiker|bauch|rotate]
package main

import (
	"errors"
	"flag"
	"fmt"
	"math"
	"math/rand/v2"
	"os"
	"runtime"
	"slices"
	"sort"
	"strconv"
	"strings"
	"sync"

	"ruderspiel/internal/bot"
	"ruderspiel/internal/data"
	"ruderspiel/internal/engine"
)

type gameStats struct {
	err         error
	personality []bot.Personality
	points      []int
	gold        []int
	silver      []int
	winners     []int // seats
	results     []engine.CompetitionResult
	draftKinds  map[bot.Personality]map[string]int
}

func main() {
	games := flag.Int("games", 500, "number of seasons")
	seed := flag.Uint64("seed", 1, "first game seed")
	players := flag.Int("players", 3, "players per game (2-4)")
	mode := flag.String("mode", "default", "personalities: default (bot.PersonalityFor), taktiker, bauch, rotate")
	workers := flag.Int("workers", runtime.NumCPU(), "parallel games")

	flag.Parse()

	out := make([]gameStats, *games)
	var wg sync.WaitGroup
	jobs := make(chan int)

	for range max(*workers, 1) {
		wg.Go(func() {
			for i := range jobs {
				out[i] = play(*seed+uint64(i), *players, personalities(*mode, *players, i)) //nolint:gosec // i >= 0
			}
		})
	}

	for i := range *games {
		jobs <- i
	}

	close(jobs)
	wg.Wait()

	for i, gs := range out {
		if gs.err != nil {
			fmt.Fprintf(os.Stderr, "game %d (seed %d): %v\n", i, *seed+uint64(i), gs.err)
			os.Exit(1)
		}
	}

	report(out, *players, *mode)
}

func personalities(mode string, n, game int) []bot.Personality {
	ps := make([]bot.Personality, n)
	for s := range ps {
		switch mode {
		case "taktiker":
			ps[s] = bot.Taktiker
		case "bauch":
			ps[s] = bot.Bauchgefuehl
		case "rotate":
			ps[s] = bot.PersonalityFor(s + game)
		default:
			ps[s] = bot.PersonalityFor(s)
		}
	}

	return ps
}

func play(seed uint64, n int, ps []bot.Personality) gameStats {
	cfg := engine.Config{Seed: seed}
	for s := range n {
		cfg.Players = append(cfg.Players,
			engine.PlayerConfig{ID: fmt.Sprintf("p%d", s), Name: fmt.Sprintf("Bot %d", s), IsBot: true})
	}

	gs := gameStats{personality: ps, draftKinds: map[bot.Personality]map[string]int{}}

	g, err := engine.New(cfg)
	if err != nil {
		gs.err = err
		return gs
	}

	rngs := make([]*rand.Rand, n)
	for s := range rngs {
		rngs[s] = rand.New(rand.NewPCG(seed, 1000+uint64(s)))
	}

	for steps := 0; !g.Over(); steps++ {
		if steps > 10000 {
			gs.err = errors.New("no game over")
			return gs
		}

		for _, pid := range g.Pending() {
			s := seatOf(pid)

			d, err := bot.Decide(g, pid, ps[s], rngs[s])
			if err != nil {
				gs.err = err
				return gs
			}

			err = g.Submit(pid, d)
			if err != nil {
				gs.err = fmt.Errorf("phase %s, %s (%s): rejected: %w", g.PhaseID(), pid, ps[s], err)
				return gs
			}

			if d.Kind == engine.PhaseDraft {
				gs.addDraftPick(ps[s], d.DraftCardID)
			}
		}
	}

	v := g.View("p0")
	for _, p := range v.Players {
		gs.points = append(gs.points, p.Points)
		gs.gold = append(gs.gold, p.Gold)
		gs.silver = append(gs.silver, p.Silver)
	}

	for _, w := range g.Winners() {
		gs.winners = append(gs.winners, seatOf(w))
	}

	gs.results = g.Results()

	return gs
}

// seatOf returns the seat of a player ID "p<seat>".
func seatOf(pid string) int {
	s, _ := strconv.Atoi(strings.TrimPrefix(pid, "p")) // IDs are generated by play

	return s
}

// addDraftPick counts a draft pick by card kind (the card ID prefix before ':').
func (gs *gameStats) addDraftPick(p bot.Personality, cardID string) {
	k, _, _ := strings.Cut(cardID, ":")

	if gs.draftKinds[p] == nil {
		gs.draftKinds[p] = map[string]int{}
	}

	gs.draftKinds[p][k]++
}

type agg struct{ n, sum float64 }

func (a *agg) add(x float64) { a.n++; a.sum += x }
func (a *agg) mean() float64 {
	if a.n == 0 {
		return 0
	}

	return a.sum / a.n
}

func pct(a, b float64) string {
	if b == 0 {
		return "   -  "
	}

	return fmt.Sprintf("%5.1f%%", 100*a/b)
}

func report(out []gameStats, n int, mode string) {
	fmt.Printf("Ruderspiel sim: %d games, %d players, personalities %s\n\n", len(out), n, mode)

	reportWins(out, n)
	reportPoints(out)
	reportRaces(out)
	reportDraft(out)
}

func reportWins(out []gameStats, players int) {
	games := float64(len(out))
	seatWins := make([]float64, players)
	persWins, persSeats := map[bot.Personality]float64{}, map[bot.Personality]float64{}
	ties := 0

	for _, gs := range out {
		if len(gs.winners) > 1 {
			ties++
		}

		for _, s := range gs.winners {
			seatWins[s] += 1 / float64(len(gs.winners))
			persWins[gs.personality[s]] += 1 / float64(len(gs.winners))
		}

		for _, p := range gs.personality {
			persSeats[p]++
		}
	}

	fmt.Println("Win rate (ties split):")

	for s := range players {
		fmt.Printf("  seat %d (%s): %s\n", s, out[0].personality[s], pct(seatWins[s], games))
	}

	for _, p := range []bot.Personality{bot.Taktiker, bot.Bauchgefuehl} {
		if persSeats[p] > 0 {
			fmt.Printf("  %-12s  %s per seat-game (fair share %s)\n",
				p, pct(persWins[p], persSeats[p]), pct(1, float64(players)))
		}
	}

	fmt.Printf("  shared wins: %s of games\n\n", pct(float64(ties), games))
}

func reportPoints(out []gameStats) {
	var all []int
	var gold, silver, spread agg
	persPts := map[bot.Personality]*agg{}

	for _, gs := range out {
		for s, p := range gs.points {
			all = append(all, p)

			gold.add(float64(gs.gold[s]))
			silver.add(float64(gs.silver[s]))

			if persPts[gs.personality[s]] == nil {
				persPts[gs.personality[s]] = &agg{}
			}

			persPts[gs.personality[s]].add(float64(p))
		}

		spread.add(float64(slices.Max(gs.points) - slices.Min(gs.points)))
	}

	sort.Ints(all)

	sum, sq := 0.0, 0.0
	inRange := 0

	for _, p := range all {
		sum += float64(p)
		if p >= 15 && p <= 40 {
			inRange++
		}
	}

	mean := sum / float64(len(all))
	for _, p := range all {
		sq += (float64(p) - mean) * (float64(p) - mean)
	}

	q := func(f float64) int { return all[int(f*float64(len(all)-1))] }
	fmt.Printf("Final points: mean %.1f (sd %.1f), min %d, p10 %d, median %d, p90 %d, max %d; in 15..40: %s\n",
		mean, math.Sqrt(sq/float64(len(all))), all[0], q(0.1), q(0.5), q(0.9), all[len(all)-1],
		pct(float64(inRange), float64(len(all))))
	fmt.Printf("  winner minus last: %.1f points on average\n", spread.mean())

	for _, p := range []bot.Personality{bot.Taktiker, bot.Bauchgefuehl} {
		if a := persPts[p]; a != nil {
			fmt.Printf("  %-12s mean %.1f points\n", p, a.mean())
		}
	}

	fmt.Printf("Medals per player and season: gold %.1f, silver %.1f\n\n", gold.mean(), silver.mean())
}

// compAgg aggregates one competition (calendar station) over all games.
type compAgg struct {
	name, kind          string
	total, entries, gst agg
}

// raceStats aggregates all non-team races over all games.
type raceStats struct {
	entries, races, guestGold, guestMedal agg
	byCount                               map[int]float64
	water, kentern, material, krebs       float64
	crew, boat, trainer, event, penalty   float64
	contested, byBoat, byTrainer          float64
	comps                                 map[int]*compAgg
}

// addRace adds one race of competition cr; ca is the competition's aggregate.
func (st *raceStats) addRace(cr engine.CompetitionResult, rr engine.RaceResult, ca *compAgg) {
	var ps []engine.EntryResult

	for _, e := range rr.Entries {
		if e.Guest != "" {
			st.addGuest(e, ca)
			continue
		}

		ps = append(ps, e)
	}

	st.races.add(1)
	st.entries.add(float64(len(ps)))
	st.byCount[len(ps)]++
	ca.entries.add(float64(len(ps)))

	for _, e := range ps {
		ca.total.add(float64(e.Total))
		st.crew += float64(e.Crew)
		st.boat += float64(e.BoatValue)
		st.trainer += float64(e.Trainer)
		st.event += float64(e.EventBonus)
		st.penalty += float64(e.Penalty)

		if cr.Weather != "" {
			st.addIncident(e.Incident)
		}
	}

	st.addDecidedBy(ps)
}

func (st *raceStats) addGuest(e engine.EntryResult, ca *compAgg) {
	if e.Place == 1 {
		st.guestGold.add(1)
		ca.gst.add(1)
	} else {
		st.guestGold.add(0)
		ca.gst.add(0)
	}

	if e.Place <= 2 && e.Place > 0 {
		st.guestMedal.add(1)
	} else {
		st.guestMedal.add(0)
	}
}

func (st *raceStats) addIncident(inc engine.IncidentKind) {
	st.water++

	switch inc {
	case engine.IncidentKentern:
		st.kentern++
	case engine.IncidentMaterial:
		st.material++
	case engine.IncidentKrebs:
		st.krebs++
	}
}

// addDecidedBy analyses whether the boat or the trainer decided between the two best finishing
// player entries.
func (st *raceStats) addDecidedBy(ps []engine.EntryResult) {
	var fin []engine.EntryResult

	for _, e := range ps {
		if e.Place > 0 && e.Incident != engine.IncidentKentern && e.Incident != engine.IncidentMaterial {
			fin = append(fin, e)
		}
	}

	if len(fin) < 2 || fin[0].Total <= fin[1].Total {
		return
	}

	st.contested++

	a, b := fin[0], fin[1]
	if a.Total-a.BoatValue < b.Total-b.BoatValue {
		st.byBoat++
	}

	if a.Total-a.Trainer < b.Total-b.Trainer {
		st.byTrainer++
	}
}

// compKind groups a competition for the guest report: Ergo-Cups, Hildesheim (Langstrecke), JTFO
// and the other water regattas.
func compKind(d *data.Data, station int) string {
	c := d.Competitions[d.Calendar[station].Competition]

	switch {
	case c.Kind == "ergocup":
		return "Ergo-Cups"
	case c.Kind == "jtfo":
		return "JTFO (team)"
	case c.Context == "langstrecke":
		return "Hildesheim"
	default:
		return "water regattas"
	}
}

func reportRaces(out []gameStats) {
	st := &raceStats{byCount: map[int]float64{}, comps: map[int]*compAgg{}}

	d, err := data.Load()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	for _, gs := range out {
		for _, cr := range gs.results {
			ca := st.comps[cr.StationIndex]
			if ca == nil {
				ca = &compAgg{name: cr.Name, kind: compKind(d, cr.StationIndex)}
				st.comps[cr.StationIndex] = ca
			}

			for _, rr := range cr.Races {
				if rr.RaceID == "team" {
					ca.addTeamGuest(rr)
				} else {
					st.addRace(cr, rr, ca)
				}
			}
		}
	}

	n := st.races.n
	fmt.Printf("Races: %.1f player entries per race; races with 0/1/2/3/4 entrants: %s / %s / %s / %s / %s\n",
		st.entries.mean(), pct(st.byCount[0], n), pct(st.byCount[1], n), pct(st.byCount[2], n),
		pct(st.byCount[3], n), pct(st.byCount[4], n))

	if st.guestGold.n > 0 {
		fmt.Printf("  guest crew placed 1st in %s and in the top 2 in %s of contested races\n",
			pct(st.guestGold.sum, st.guestGold.n), pct(st.guestMedal.sum, st.guestMedal.n))
	}

	fmt.Printf("  races between >=2 finishing players: %s; of those decided by the boat %s, by the trainer %s\n",
		pct(st.contested, n), pct(st.byBoat, st.contested), pct(st.byTrainer, st.contested))
	fmt.Printf("Incidents per water entry: Kentern %s, Material %s, Krebs %s\n",
		pct(st.kentern, st.water), pct(st.material, st.water), pct(st.krebs, st.water))

	tot := st.crew + st.boat + st.trainer + st.event
	fmt.Printf("Score sources (all player entries): crew %s, boat %s, trainer %s, events %s; Krebs penalties %s\n\n",
		pct(st.crew, tot), pct(st.boat, tot), pct(st.trainer, tot), pct(st.event, tot), pct(st.penalty, tot))

	fmt.Println("Per competition: mean entry total, entries per race, guest crew 1st")

	keys := make([]int, 0, len(st.comps))
	for k := range st.comps {
		keys = append(keys, k)
	}

	sort.Ints(keys)

	for _, k := range keys {
		ca := st.comps[k]
		fmt.Printf("  %-30s %6.1f  %.2f  %s\n", ca.name, ca.total.mean(), ca.entries.mean(), pct(ca.gst.sum, ca.gst.n))
	}

	reportGuestKinds(st.comps)
}

// reportGuestKinds prints the guest crew's 1st-place rate per competition type.
func reportGuestKinds(comps map[int]*compAgg) {
	kinds := map[string]*agg{}

	for _, ca := range comps {
		if kinds[ca.kind] == nil {
			kinds[ca.kind] = &agg{}
		}

		kinds[ca.kind].n += ca.gst.n
		kinds[ca.kind].sum += ca.gst.sum
	}

	fmt.Print("Guest crew 1st by type:")

	for _, k := range []string{"Ergo-Cups", "water regattas", "Hildesheim", "JTFO (team)"} {
		if a := kinds[k]; a != nil {
			fmt.Printf(" %s %s;", k, pct(a.sum, a.n))
		}
	}

	fmt.Println()
}

// addTeamGuest counts whether the guest team won a team ranking (JTFO).
func (ca *compAgg) addTeamGuest(rr engine.RaceResult) {
	for _, e := range rr.Entries {
		if e.Guest == "" {
			continue
		}

		if e.Place == 1 {
			ca.gst.add(1)
		} else {
			ca.gst.add(0)
		}
	}
}

func reportDraft(out []gameStats) {
	fmt.Println("\nDraft picks:")

	for _, p := range []bot.Personality{bot.Taktiker, bot.Bauchgefuehl} {
		kinds := map[string]float64{}
		total := 0.0

		for _, gs := range out {
			for k, c := range gs.draftKinds[p] {
				kinds[k] += float64(c)
				total += float64(c)
			}
		}

		if total > 0 {
			fmt.Printf("  %-12s rower %s, boat %s, trainer %s\n",
				p, pct(kinds["rower"], total), pct(kinds["boat"], total), pct(kinds["trainer"], total))
		}
	}
}
